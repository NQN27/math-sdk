def read_reel_csv(path):
    with open(path, newline="") as f:
        rows = [r for r in csv.reader(f) if r]
    num_reels = len(rows[0])
    strips = [[] for _ in range(num_reels)]
    for row in rows:
        for i, sym in enumerate(row):
            strips[i].append(sym.strip())
    return strips

stages = {}
for s in range(1, 7):
    strips = read_reel_csv(f"{REELS_DIR}\\BM_Reels_S{s}.csv")
    stages[str(s)] = strips
    print(f"stage {s}: {len(strips)} reels, lengths {[len(x) for x in strips]}")

with open(OUT, "w") as f:
    f.write("// Real reel strips for Normal-tier Bonus, embedded verbatim from\n")
    f.write("// games/0_0_boss_lines/reels/BM_Reels_S1..S6.csv (one array per reel,\n")
    f.write("// per-stage). Generated by gen_reel_data.py - do not hand-edit.\n")
    f.write("const REEL_STRIPS = ")
    f.write(json.dumps(stages))
    f.write(";\n")

