"""Generates web-sdk apps/boss-lines/src/game/config.ts straight from the
math-sdk's own generated config_fe_0_0_boss_lines.json - no hand-edited
values, so the frontend can never drift from the backend config.

json.dumps produces valid TS object-literal syntax (quoted keys are legal
TS), so this is a lossless serialization of the backend file.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME_DIR = os.path.dirname(HERE)
SRC = os.path.join(GAME_DIR, "library", "configs", "config_fe_0_0_boss_lines.json")


def main(out_path):
    cfg = json.load(open(SRC, encoding="utf-8"))

    # math-sdk emits symbols as a list of single-key dicts; the frontend's
    # `SymbolName = keyof typeof config.symbols` needs a flat object.
    if isinstance(cfg["symbols"], list):
        flat = {}
        for entry in cfg["symbols"]:
            flat.update(entry)
        cfg["symbols"] = flat

    body = json.dumps(cfg, indent=1)
    ts = (
        "// GENERATED by math-sdk games/0_0_boss_lines/_tuning_scratch/"
        "gen_webfe_config.py\n"
        "// Source: library/configs/config_fe_0_0_boss_lines.json - do not hand-edit.\n"
        f"export default {body} as const;\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(ts)
    print(f"wrote {out_path} ({len(ts)} bytes)")
    print("symbols:", sorted(cfg["symbols"]))
    print("betModes:", sorted(cfg["betModes"]))
    print("gameTypes:", sorted(cfg["paddingReels"]))


if __name__ == "__main__":
    main(sys.argv[1])
